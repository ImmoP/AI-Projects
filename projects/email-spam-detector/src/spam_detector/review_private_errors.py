def parse_arguments():
    """
    Parse command-line mode.
    """

    parser = argparse.ArgumentParser(
        description=(
            "Prepare or score the complete private "
            "validation manual review."
        )
    )

    parser.add_argument(
        "mode",
        choices=[
            "prepare",
            "score",
        ],
        help=(
            "prepare creates the complete review CSV; "
            "score calculates metrics after review."
        ),
    )

    return parser.parse_args()


def main() -> None:
    """
    Run the requested review operation.
    """

    arguments = (
        parse_arguments()
    )

    if arguments.mode == "prepare":

        prepare_review_file()

    elif arguments.mode == "score":

        score_completed_review()


if __name__ == "__main__":
    main()