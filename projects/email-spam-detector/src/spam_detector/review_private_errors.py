"""
Prepare and score a complete manual review of private validation errors.

This script works with the predictions already generated by:

    analyze_private_errors.py

No GPT-2 inference is required again.

Two modes are available:

    prepare
        Creates one CSV containing ALL private validation errors.
        Existing manual decisions from manual_review_sample.csv are
        imported automatically.

    score
        Reads the completed manual review and recalculates the
        private validation metrics using the manually adjudicated
        labels.

Usage:

    python -m spam_detector.review_private_errors prepare

    python -m spam_detector.review_private_errors score
"""

